<section aria-labelledby="privacidade">
	<h2 id="privacidade">Privacidade</h2>
	<ul>
		<li>Não há cadastro nem login.</li>
		<li>Não usamos cookies nem ferramentas de análise de audiência.</li>
		<li>Não carregamos recursos de terceiros: fontes, scripts e imagens vêm do próprio site.</li>
		<li>
			Quando houver preferências (por exemplo, tamanho do texto), elas ficarão apenas no seu
			navegador.
		</li>
		<li>
			Como em qualquer site, o serviço de hospedagem pode registrar dados técnicos de acesso, como
			endereço IP e página visitada. A política do provedor será informada aqui antes da publicação.
		</li>
	</ul>
</section>

