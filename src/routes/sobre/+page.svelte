<section aria-labelledby="o-que-e">
	<h2 id="o-que-e">O que é</h2>
	<p>
		O Catoolicas é um projeto comunitário de software livre que reúne ferramentas para a vida de
		oração, o estudo e a prática da fé católica. Ele complementa os canais e bots da comunidade no
		Telegram, sem substituí-los.
	</p>
