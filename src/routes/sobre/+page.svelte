<h1>Sobre o projeto</h1>

<section aria-labelledby="o-que-e">
	<h2 id="o-que-e">O que é</h2>
	<p>
		O Catoolicas é um projeto comunitário de software livre que reúne ferramentas para a vida de
		oração, o estudo e a prática da fé católica. Ele complementa os canais e bots da comunidade no
		Telegram, sem substituí-los.
	</p>
	<p class="rubrica">
		O site está em desenvolvimento e ainda não oferece as ferramentas previstas.
	</p>
</section>

<section aria-labelledby="privacidade">
	<h2 id="privacidade">Privacidade</h2>
	<ul>
		<li>Não há cadastro nem login.</li>
		<li>Não usamos cookies nem ferramentas de análise de audiência.</li>
		<li>Não carregamos recursos de terceiros: fontes, scripts e imagens vêm do próprio site.</li>
		<li>
			No Terço, as preferências e o ponto em que você parou ficam apenas neste navegador, e só
			depois que você avança ou muda uma preferência. O botão "Apagar dados deste aparelho", nas
			Preferências, apaga tudo.
		</li>
		<li>
			No Exame de consciência, nada do que você marca ou escreve é enviado ou gravado: fica só na
			memória da página e se apaga ao fechá-la, recarregá-la ou sair dela.
		</li>
		<li>
			Para funcionar sem internet, o navegador guarda uma cópia das páginas e dos arquivos do site
			depois que você abre o Terço ou o Exame. É só o conteúdo público do site, nunca o que você faz
			nele. Para apagar essa cópia, limpe os dados do site nas configurações do navegador.
		</li>
		<li>
			O site é hospedado no GitHub Pages. Segundo a
			<a
				href="https://docs.github.com/en/pages/getting-started-with-github-pages/what-is-github-pages#data-collection"
				rel="external noopener noreferrer"
			>
				documentação do GitHub
			</a>, o endereço IP de quem visita é registrado e guardado pelo GitHub por motivos de
			segurança. Esse registro é do GitHub, não deste projeto, e não inclui nada do que você faz
			dentro das páginas.
		</li>
	</ul>
</section>

